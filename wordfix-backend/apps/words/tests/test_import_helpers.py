class TestTextCleaner:
    """Tests for text_cleaner module."""

    def test_removes_urls(self):
        text = "Learn at http://example.com or https://foo.bar/baz"
        result = clean_imported_text(text)
        assert "http" not in result
        assert "example.com" not in result

    def test_removes_money_patterns(self):
        text = "Price: $49.99 or 100 000 so'm"
        result = clean_imported_text(text)
        assert "$49.99" not in result

    def test_removes_branding(self):
        text = "Powered by NotebookLM\nGenerated by ChatGPT\nHello world"
        result = clean_imported_text(text)
        assert "NotebookLM" not in result
        assert "ChatGPT" not in result
        assert "Hello world" in result

    def test_removes_instruction_lines(self):
        text = "Click here to download\nTap to listen\nApple – olma"
        result = clean_imported_text(text)
        assert "Click here" not in result
        assert "Tap to listen" not in result
        assert "Apple" in result

    def test_removes_short_garbage(self):
        text = "ab\nxy\nHello – salom\nk"
        result = clean_imported_text(text)
        assert "ab" not in result.split("\n")[0] if result.strip() else True
        assert "Hello" in result

    def test_normalizes_blank_lines(self):
        text = "Line 1\n\n\n\n\nLine 2"
        result = clean_imported_text(text)
        # Should not have 5 blank lines
        assert "\n\n\n" not in result

    def test_preserves_valid_content(self):
        text = "1. Clap – qarsak chalmoq\n2. Smile – jilmaymoq"
        result = clean_imported_text(text)
        assert "Clap" in result
        assert "Smile" in result

    def test_extract_sections(self):
        text = """Unit 6: Our Favorite Hobbies
1. Clap – qarsak chalmoq

Unit 7: Animals
2. Kangaroo – kenguru"""
        sections = extract_document_sections(text)
        assert len(sections) >= 2
        assert "Unit 6" in sections[0]["title"] or "Unit 7" in sections[1]["title"]

    def test_real_pdf_noise_removal(self):
        """Simulate real PDF import noise."""
        noisy_text = """Sources
https://example.com/vocab-list.pdf

Fly English — Beginner Vocabulary

Unit 9: Health and Body
Share with friends · Download PDF

1. Headache – bosh og'rig'i
2. Medicine – dori
3. Fever – isitma

Generated by NotebookLM
© 2024 All Rights Reserved"""
        result = clean_imported_text(noisy_text)
        assert "https://" not in result
        assert "NotebookLM" not in result
        assert "© 2024" not in result or "All Rights Reserved" not in result
        assert "Headache" in result
        assert "Medicine" in result
        assert "Fever" in result


