def estimate_cefr(word: str) -> str:
    """Estimate CEFR level for a word."""
    w = word.lower().strip()

    # Known words
    if w in CEFR_KNOWN:
        return CEFR_KNOWN[w]

    # Heuristic based on word length
    length = len(w)
    if length <= 4:
        return "A1"
    elif length <= 6:
        return "A2"
    elif length <= 8:
        return "B1"
    elif length <= 10:
        return "B2"
    else:
        return "C1"
