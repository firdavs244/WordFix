class TestSmartImportIntegration:
    """Integration tests for the full smart import pipeline."""

    def test_full_pdf_text_pipeline(self):
        """Simulate real PDF text import — clean → extract → enrich."""

        pdf_text = """Sources
https://example.com/vocab.pdf

Fly English — Beginner Vocabulary

Unit 9: Health and Body
Share with friends

1. Headache – bosh og'rig'i
2. Medicine – dori
3. Fever – isitma
4. Cough – yo'tal
5. Sneeze – aksirmoq

Unit 10: Food and Kitchen
6. Recipe – retsept
7. Delicious – mazali
8. Ingredient – tarkibiy qism
9. Dessert – desert
10. Slice – tilim

Unit 11: Travel
11. Adventure – sarguzasht
12. Passenger – yo'lovchi
13. Luggage – yuk
14. Departure – jo'nash
15. Destination – manzil

Generated by NotebookLM
© 2024"""

        # Step 1: Clean
        cleaned = clean_imported_text(pdf_text)
        assert "NotebookLM" not in cleaned
        assert "https://" not in cleaned
        assert "Headache" in cleaned
        assert "Adventure" in cleaned

        # Step 2: Extract pairs
        pairs = extract_word_pairs(cleaned)
        assert len(pairs) >= 15, f"Expected 15+ pairs, got {len(pairs)}"

        words = [p["word"].lower() for p in pairs]
        assert "headache" in words
        assert "medicine" in words
        assert "adventure" in words
        assert "destination" in words

        # Check no noise words
        for noise in ["notebooklm", "https", "sources", "share", "download"]:
            assert noise not in words, f"Noise word '{noise}' should not be extracted"

        # Step 3: Translation lookup
        for pair in pairs:
            word = pair["word"].lower()
            trans = get_translation(word)
            if trans:
                assert len(trans) > 0

