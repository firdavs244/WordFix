class TestPairExtractor:
    """Tests for pair_extractor module."""

    def test_numbered_pairs(self):
        text = """1. Headache – bosh og'rig'i
2. Medicine – dori
3. Fever – isitma"""
        pairs = extract_word_pairs(text)
        assert len(pairs) >= 3
        words = [p["word"].lower() for p in pairs]
        assert "headache" in words
        assert "medicine" in words
        assert "fever" in words

    def test_dash_pairs(self):
        text = """Clap – qarsak chalmoq
Smile – jilmaymoq
Kick – tepmoq"""
        pairs = extract_word_pairs(text)
        assert len(pairs) >= 3
        words = [p["word"].lower() for p in pairs]
        assert "clap" in words
        assert "smile" in words

    def test_multi_unit_text(self):
        text = """Unit 6: Our Favorite Hobbies
1. Clap – qarsak chalmoq
2. Choose – tanlamoq

Unit 7: Animals and Nature
3. Kangaroo – kenguru
4. Dolphin – delfin"""
        pairs = extract_word_pairs(text)
        assert len(pairs) >= 4
        words = [p["word"].lower() for p in pairs]
        assert "clap" in words
        assert "kangaroo" in words

    def test_confidence_scores(self):
        text = "1. Headache – bosh og'rig'i"
        pairs = extract_word_pairs(text)
        assert len(pairs) >= 1
        assert "confidence" in pairs[0]
        assert pairs[0]["confidence"] >= 0.8

    def test_deduplication(self):
        text = """1. Clap – qarsak chalmoq
2. Clap – qarsak
Clap – qarsak chalmoq"""
        pairs = extract_word_pairs(text)
        clap_count = sum(1 for p in pairs if p["word"].lower() == "clap")
        assert clap_count == 1

    def test_filters_noise(self):
        """OCR noise and Uzbek words should be filtered out."""
        text = """1. Headache – bosh og'rig'i
bonmo – tlae
maqsad – goal
2. Medicine – dori"""
        pairs = extract_word_pairs(text)
        words_lower = [p["word"].lower() for p in pairs]
        assert "headache" in words_lower
        assert "medicine" in words_lower
        # "bonmo" is noise, "maqsad" is Uzbek — should be filtered
        assert "bonmo" not in words_lower
        assert "maqsad" not in words_lower

    def test_empty_text(self):
        assert extract_word_pairs("") == []
        assert extract_word_pairs("   ") == []

    def test_no_pairs_in_plain_text(self):
        """Plain English text without dash pairs → returns few or no pairs."""
        text = "The quick brown fox jumps over the lazy dog."
        pairs = extract_word_pairs(text)
        # Should not extract random words as pairs
        assert len(pairs) <= 2


